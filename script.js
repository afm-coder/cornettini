/* =========================================================
   FIND SPARKLE CONTAINER
   ========================================================= */

const sparkleContainer =
    document.getElementById(
        "sparkles"
    );


/* =========================================================
   SPARKLE TYPES
   ========================================================= */

const sparkleTypes = [

    "✦",
    "✦",
    "✦",
    "✦",

    "✧",
    "✧",

    "⋆",

    "✦",
    "✧",
    "✦"

];


/* =========================================================
   CREATE SPARKLE
   ========================================================= */

function createSparkle() {


    /* =====================================================
       CREATE SPAN
       ===================================================== */

    const sparkle =
        document.createElement(
            "span"
        );


    /* =====================================================
       ADD CLASS
       ===================================================== */

    sparkle.className =
        "sparkle";


    /* =====================================================
       CHOOSE RANDOM STAR
       ===================================================== */

    sparkle.textContent =
        sparkleTypes[
            Math.floor(
                Math.random() *
                sparkleTypes.length
            )
        ];


    /* =====================================================
       RANDOM HORIZONTAL POSITION

       1vw → 99vw
       ===================================================== */

    sparkle.style.left =
        (
            Math.random() * 98 + 1
        ) + "vw";


    /* =====================================================
       RANDOM VERTICAL POSITION

       1vh → 99vh
       ===================================================== */

    sparkle.style.top =
        (
            Math.random() * 98 + 1
        ) + "vh";


    /* =====================================================
       MASSIVE RANDOM STAR SIZE

       40px → 75px
       ===================================================== */

    const size =
        Math.random() * 35 + 40;


    sparkle.style.fontSize =
        size + "px";


    /* =====================================================
       RANDOM ANIMATION DURATION

       3s → 6s
       ===================================================== */

    const duration =
        Math.random() * 3 + 3;


    sparkle.style.setProperty(

        "--duration",

        duration + "s"

    );


    /* =====================================================
       ADD STAR TO CONTAINER
       ===================================================== */

    sparkleContainer.appendChild(
        sparkle
    );


    /* =====================================================
       REMOVE STAR AFTER ANIMATION
       ===================================================== */

    setTimeout(

        function () {

            sparkle.remove();

        },

        (duration * 1000) + 300

    );

}


/* =========================================================
   MASSIVE INITIAL STAR BURST
   =========================================================

   40 stars appear during the first second.
   ========================================================= */

for (

    let i = 0;

    i < 40;

    i++

) {

    setTimeout(

        createSparkle,

        Math.random() * 1000

    );

}


/* =========================================================
   CONTINUOUS STAR GENERATION
   =========================================================

   A new star appears every 180ms.

   This creates a LOT of simultaneous stars.
   ========================================================= */

setInterval(

    function () {

        createSparkle();

    },

    180

);


/* =========================================================
   =========================================================
   CLUB RADIO
   =========================================================
   ========================================================= */


/* =========================================================
   FIND RADIO BUTTON
   ========================================================= */

const radioButton =
    document.getElementById(
        "radioButton"
    );


/* =========================================================
   FIND YOUTUBE PLAYER
   ========================================================= */

const clubPlayer =
    document.getElementById(
        "clubplayer"
    );


/* =========================================================
   RADIO BUTTON CLICK
   ========================================================= */

radioButton.addEventListener(

    "click",

    function () {


        /* =================================================
           CURRENT STATE = OFF
           
           START MUSIC
           ================================================= */

        if (

            this.getAttribute(
                "data-state"
            ) === "off"

        ) {


            /* =============================================
               LOAD YOUTUBE VIDEO
               ============================================= */

            clubPlayer.src =
                "https://www.youtube.com/embed/8F2s8ivKXNY?autoplay=1";


            /* =============================================
               CHANGE BUTTON TEXT
               ============================================= */

            this.innerHTML =
                "⟳ Restart";


            /* =============================================
               CHANGE STATE
               ============================================= */

            this.setAttribute(

                "data-state",

                "restart"

            );

        }


        /* =================================================
           CURRENT STATE = RESTART
           
           STOP MUSIC
           ================================================= */

        else {


            /* =============================================
               REMOVE PLAYER SOURCE
               ============================================= */

            clubPlayer.src =
                "";


            /* =============================================
               RESET BUTTON
               ============================================= */

            this.innerHTML =
                "▶ Play Music";


            /* =============================================
               RESET STATE
               ============================================= */

            this.setAttribute(

                "data-state",

                "off"

            );

        }

    }

);
