/* =========================================================
   FIND SPARKLE CONTAINER
   ========================================================= */

const sparkleContainer =
    document.getElementById(
        "sparkles"
    );


/* =========================================================
   SPARKLE TYPES
   ========================================================= */

const sparkleTypes = [

    "✦",

    "✦",

    "✦",

    "✦",

    "⋆"

];


/* =========================================================
   CREATE SPARKLE
   ========================================================= */

function createSparkle() {


    const sparkle =
        document.createElement(
            "span"
        );


    sparkle.className =
        "sparkle";


    /* =====================================================
       CHOOSE STAR
       ===================================================== */

    sparkle.textContent =
        sparkleTypes[
            Math.floor(
                Math.random() *
                sparkleTypes.length
            )
        ];


    /* =====================================================
       POSITION INSIDE SIDEBAR
       ===================================================== */

    sparkle.style.left =
        (
            Math.random() * 94 + 3
        ) + "%";


    sparkle.style.top =
        (
            Math.random() * 94 + 3
        ) + "%";


    /* =====================================================
       RANDOM SIZE
       ===================================================== */

    const size =
        Math.random() * 5 + 8;


    sparkle.style.fontSize =
        size + "px";


    /* =====================================================
       RANDOM ANIMATION LENGTH
       ===================================================== */

    const duration =
        Math.random() * 2.5 + 2.5;


    sparkle.style.setProperty(

        "--duration",

        duration + "s"

    );


    /* =====================================================
       ADD STAR
       ===================================================== */

    sparkleContainer.appendChild(
        sparkle
    );


    /* =====================================================
       REMOVE STAR
       ===================================================== */

    setTimeout(

        function () {

            sparkle.remove();

        },

        (duration * 1000) + 200

    );

}


/* =========================================================
   INITIAL STAR BURST
   ========================================================= */

for (

    let i = 0;

    i < 8;

    i++

) {

    setTimeout(

        createSparkle,

        Math.random() * 500

    );

}


/* =========================================================
   CONTINUOUS STAR GENERATION
   ========================================================= */

setInterval(

    function () {

        createSparkle();

    },

    700

);


/* =========================================================
   =========================================================
   CLUB RADIO
   =========================================================
   ========================================================= */


/* =========================================================
   FIND RADIO BUTTON
   ========================================================= */

const radioButton =
    document.getElementById(
        "radioButton"
    );


/* =========================================================
   FIND YOUTUBE PLAYER
   ========================================================= */

const clubPlayer =
    document.getElementById(
        "clubplayer"
    );


/* =========================================================
   RADIO BUTTON CLICK
   ========================================================= */

radioButton.addEventListener(

    "click",

    function () {


        /* =================================================
           CURRENT STATE = OFF

           START MUSIC
           ================================================= */

        if (

            this.getAttribute(
                "data-state"
            ) === "off"

        ) {


            /* =============================================
               LOAD YOUTUBE VIDEO

               THIS IS THE ORIGINAL WORKING METHOD
               ============================================= */

            clubPlayer.src =
                "https://www.youtube.com/embed/8F2s8ivKXNY?autoplay=1";


            /* =============================================
               CHANGE BUTTON TEXT
               ============================================= */

            this.innerHTML =
                "⟳ Restart";


            /* =============================================
               CHANGE STATE
               ============================================= */

            this.setAttribute(

                "data-state",

                "restart"

            );

        }


        /* =================================================
           CURRENT STATE = RESTART

           STOP MUSIC
           ================================================= */

        else {


            /* =============================================
               REMOVE PLAYER SOURCE
               ============================================= */

            clubPlayer.src =
                "";


            /* =============================================
               RESET BUTTON
               ============================================= */

            this.innerHTML =
                "▶ Play Music";


            /* =============================================
               RESET STATE
               ============================================= */

            this.setAttribute(

                "data-state",

                "off"

            );

        }

    }

);
