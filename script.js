/* =========================================================
   FIND SPARKLE CONTAINER
   ========================================================= */

const sparkleContainer =
    document.getElementById(
        "sparkles"
    );


/* =========================================================
   SPARKLE TYPES
   ========================================================= */

const sparkleTypes = [

    "✦",

    "✦",

    "✦",

    "⋆",

    "✦"

];


/* =========================================================
   CREATE SPARKLE
   ========================================================= */

function createSparkle() {


    const sparkle =
        document.createElement(
            "span"
        );


    sparkle.className =
        "sparkle";


    sparkle.textContent =
        sparkleTypes[
            Math.floor(
                Math.random() *
                sparkleTypes.length
            )
        ];


    /* =====================================================
       KEEP STARS INSIDE SIDEBAR
       ===================================================== */

    sparkle.style.left =
        (
            Math.random() * 94 + 3
        ) + "%";


    sparkle.style.top =
        (
            Math.random() * 94 + 3
        ) + "%";


    /* =====================================================
       STAR SIZE
       ===================================================== */

    const size =
        Math.random() * 6 + 10;


    sparkle.style.fontSize =
        size + "px";


    /* =====================================================
       ANIMATION DURATION
       ===================================================== */

    const duration =
        Math.random() * 2.5 + 2.5;


    sparkle.style.setProperty(

        "--duration",

        duration + "s"

    );


    sparkleContainer.appendChild(
        sparkle
    );


    /* =====================================================
       REMOVE AFTER ANIMATION
       ===================================================== */

    setTimeout(

        function () {

            sparkle.remove();

        },

        (duration * 1000) + 250

    );

}


/* =========================================================
   INITIAL STAR BURST
   ========================================================= */

for (

    let i = 0;

    i < 9;

    i++

) {

    setTimeout(

        createSparkle,

        Math.random() * 500

    );

}


/* =========================================================
   CONTINUOUS STAR GENERATION
   ========================================================= */

setInterval(

    function () {

        createSparkle();

    },

    650

);


/* =========================================================
   =========================================================
   CLUB RADIO
   =========================================================
   ========================================================= */


/* =========================================================
   FIND RADIO BUTTON
   ========================================================= */

const radioButton =
    document.getElementById(
        "radioButton"
    );


/* =========================================================
   FIND YOUTUBE PLAYER
   ========================================================= */

const clubPlayer =
    document.getElementById(
        "clubplayer"
    );


/* =========================================================
   MUSIC URL
   ========================================================= */

const musicURL =
    "https://www.youtube.com/embed/8F2s8ivKXNY?autoplay=1&playsinline=1";


/* =========================================================
   RADIO BUTTON CLICK
   ========================================================= */

radioButton.addEventListener(

    "click",

    function () {


        /* =================================================
           MUSIC IS CURRENTLY OFF
           ================================================= */

        if (

            this.dataset.state === "off"

        ) {


            /* =============================================
               LOAD MUSIC
               ============================================= */

            clubPlayer.src =
                musicURL;


            /* =============================================
               CHANGE BUTTON
               ============================================= */

            this.innerHTML =
                "⏹ Stop Music";


            /* =============================================
               CHANGE STATE
               ============================================= */

            this.dataset.state =
                "playing";

        }


        /* =================================================
           MUSIC IS CURRENTLY PLAYING
           ================================================= */

        else {


            /* =============================================
               STOP MUSIC COMPLETELY
               ============================================= */

            clubPlayer.src =
                "about:blank";


            /* =============================================
               RESET BUTTON
               ============================================= */

            this.innerHTML =
                "▶ Play Music";


            /* =============================================
               RESET STATE
               ============================================= */

            this.dataset.state =
                "off";

        }

    }

);
